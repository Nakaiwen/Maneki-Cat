(function(root){
 'use strict';
 function buildPrompt(cast, style='warm'){
  if(!cast || !cast.lot || !Array.isArray(cast.lot.lines) || cast.lot.lines.length!==4)throw new Error('籤詩資料不完整');
  const lot=cast.lot,q=(cast.question||'').trim();
  return [
   '我想透過雷雨師一百籤，陪自己看一件事。請用繁體中文解讀。',
   '【工具】Nakai Wen・招財貓求籤 v0.2.4',
   '【求籤時間】'+cast.date+'（Asia/Taipei，台灣 UTC+8）',
   '',
   '【我想問的事】',
   q || '（未填寫）請先解釋這首籤詩的一般寓意；你不知道我心裡的問題，請不要替我編造事件，若需針對事情解讀，請先請我補充。',
   '',
   '【求籤方式】',
   '點擊招財貓的手，招手三下後，由程式在 1–100 籤中等機率隨機抽出一籤。',
   '【籤本】雷雨師一百籤／關聖帝君靈籤',
   '【籤號】第 '+lot.id+' 籤',
   '【傳統籤等】'+lot.grade+'（沿用所列來源的標示）',
   '',
   '【籤詩原文】',
   ...lot.lines,
   '',
   '【原文出處】'+lot.sourceName,
   lot.sourceUrl,
   '不同流傳版本可能有異文；本次解讀請以上列四句為準，不自行替換成另一版本。',
   '',
   '【請你這樣解籤】',
   '1. 先用一句話說明整首籤的核心提醒，再逐句白話解釋，最後回到整首籤的脈絡。',
   '2. 如果我有填問題，請把籤意對應到問題，分清楚「已知事實」「籤意推論」「待觀察事項」。說明支持與限制，不編造他人心理、隱藏事件、成功機率或必然發生的日期。',
   '3. 吉凶等第是傳統籤面標示，請結合籤文與問題解讀；不把上籤當成成功保證，也不把下籤當成命運判決。',
   '4. 引文以提供的籤詩為準，白話解釋請明確標成解釋。若要補充典故、聖意、東坡解或碧仙註，需能核對對應籤號與出處；資料不足就說明，不自行補寫成古文。',
   '5. 請專注這首雷雨師籤，不另行起卦或混入未提供的命盤資料。',
   style==='plain'
    ? '6. 語氣選擇：平實中立。直接、清楚地說明，不需要安慰式語句；遇到凶險字眼，也以可觀察、可調整的方向說明。'
    : '6. 語氣選擇：溫柔陪伴。溫暖、具體、不恐嚇，將凶險字眼轉譯為提醒和調整的方向，同時保留籤文原本的限制。',
   '7. 不下宿命結論、不預測疾病或災禍、不保證財務結果，也不替我做決定。',
   '8. 結尾請給我 3 個具體可觀察的重點，以及今天就能做的一件小事。',
  ].join('\n');
 }
 if(typeof module==='object'&&module.exports)module.exports={buildPrompt};
 else root.ManekiPrompt={buildPrompt};
})(typeof window!=='undefined'?window:globalThis);
